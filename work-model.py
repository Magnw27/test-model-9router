#!/usr/bin/env python3
"""Print and export successful models ordered by fastest measured latency.

Reads test_state.json generated by test_all_models.py.
"""
import argparse
import json
import os
import sys
from datetime import datetime

STATE_FILE = "test_state.json"
TEXT_OUTPUT = "work_models.txt"
JSON_OUTPUT = "work_models.json"


def color(text, code):
    if sys.stdout.isatty() and not os.getenv("NO_COLOR"):
        return f"\033[{code}m{text}\033[0m"
    return text


def main():
    parser = argparse.ArgumentParser(
        description="List successfully tested 9Router models from fastest to slowest."
    )
    parser.add_argument("--limit", type=int, default=0, help="show only the top N models; 0 means all")
    parser.add_argument("--provider", default="", help="filter providers, comma-separated (e.g. google,openai)")
    parser.add_argument("--tools", action="store_true", help="only include models confirmed to support tool calling")
    parser.add_argument("--no-export", action="store_true", help="print only; do not write output files")
    args = parser.parse_args()

    if args.limit < 0:
        parser.error("--limit cannot be negative")
    if not os.path.isfile(STATE_FILE):
        raise SystemExit(f"{STATE_FILE} not found. Run python test_all_models.py first.")

    try:
        with open(STATE_FILE, encoding="utf-8") as file:
            state = json.load(file)
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"Cannot read {STATE_FILE}: {exc}")

    models = state.get("models", {}) if isinstance(state, dict) else {}
    provider_filter = {
        name.strip().lower() for name in args.provider.split(",") if name.strip()
    }

    successful = []
    for model_id, result in models.items():
        if not isinstance(result, dict) or result.get("status") != "OK":
            continue
        latency = result.get("latency")
        if not isinstance(latency, (int, float)):
            continue
        provider = model_id.split("/", 1)[0].lower() if "/" in model_id else "unknown"
        if provider_filter and provider not in provider_filter:
            continue
        if args.tools and result.get("tools") is not True:
            continue
        successful.append({
            "model": model_id,
            "provider": provider,
            "latency": round(float(latency), 3),
            "tier": result.get("tier", "UNKNOWN"),
            "tools": result.get("tools"),
            "tested_at": result.get("tested_at"),
            "attempts": result.get("attempts"),
        })

    successful.sort(key=lambda item: (item["latency"], item["model"].lower()))
    if args.limit:
        successful = successful[:args.limit]

    print(f"\nFASTEST WORKING MODELS — {len(successful)} result(s)")
    print(f"{'RANK':>4}  {'LATENCY':>9}  {'TIER':<7}  {'TOOLS':<6}  MODEL")
    print("-" * 82)
    for index, item in enumerate(successful, start=1):
        tier = item["tier"]
        tier_color = "32" if tier == "FAST" else "33" if tier == "NORMAL" else "31"
        tools_label = "YES" if item["tools"] is True else "NO" if item["tools"] is False else "?"
        print(
            f"{index:>4}  {item['latency']:>8.3f}s  "
            f"{color(tier, tier_color):<7}  {tools_label:<6}  {item['model']}"
        )

    if not successful:
        if args.tools:
            print("\nNo successful models with tools=YES. Run python test_all_models.py --tools.")
        else:
            print("\nNo successful model results yet. Run python test_all_models.py.")
        return

    if not args.no_export:
        try:
            with open(TEXT_OUTPUT + ".tmp", "w", encoding="utf-8", newline="\n") as file:
                file.write("\n".join(item["model"] for item in successful) + "\n")
            os.replace(TEXT_OUTPUT + ".tmp", TEXT_OUTPUT)

            export = {
                "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
                "count": len(successful),
                "sort": "latency ascending",
                "models": successful,
            }
            with open(JSON_OUTPUT + ".tmp", "w", encoding="utf-8") as file:
                json.dump(export, file, ensure_ascii=False, indent=2)
                file.write("\n")
            os.replace(JSON_OUTPUT + ".tmp", JSON_OUTPUT)
        except OSError as exc:
            raise SystemExit(f"Could not export result files: {exc}")

        print(f"\nSaved ranked model IDs to {TEXT_OUTPUT}")
        print(f"Saved benchmark details to {JSON_OUTPUT}")


if __name__ == "__main__":
    main()
